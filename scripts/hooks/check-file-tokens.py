#!/usr/bin/env python3
"""Fail a commit when a staged, agent-authored file is over a token budget.

    check-file-tokens.py [--max-tokens N] <path>...
    check-file-tokens.py --help

Meant for a lefthook pre-commit job, given {staged_files}. Tokens are estimated as
bytes / 4 of the staged blob (what will be committed, not the working tree); a path
the index doesn't have is ignored. Skipped, because no agent writes them by hand:

- lockfiles (package-lock.json, pnpm-lock.yaml, *.lock, go.sum, ...)
- minified bundles, source maps and test snapshots (*.min.js, *.map, *.snap, ...)
- tabular and geographic data (*.csv, *.tsv, *.geojson, *.jsonl, *.gpx, *.kml, ...)
- anything under a vendor/, third_party/, node_modules/ or bower_components/ folder
- binary files: a NUL byte in the first 8000 bytes (git's own test), or bytes that
  aren't UTF-8 (a PDF has no NUL up front but is no text an agent writes)
- files git attributes mark linguist-generated or linguist-vendored (.gitattributes)
- files whose first lines carry a codegen header: "@generated", or a comment line that
  says "DO NOT EDIT" or opens with "auto-generated" / "generated by" (Markdown: an HTML
  comment). A comment that only mentions generated code doesn't count.

Prints each file over the budget, with instructions for splitting it, on stderr.
Exits 0 when every file fits, 1 when any is over, 2 on bad usage. Stdlib only.
"""

import argparse
import fnmatch
import math
import os
import re
import subprocess
import sys

CHARS_PER_TOKEN = 4
TARGET = (
    0.75  # split to this share of the budget, so the next edit doesn't tip it back over
)

LOCKFILES = {
    "package-lock.json",
    "npm-shrinkwrap.json",
    "pnpm-lock.yaml",
    "yarn.lock",
    "bun.lockb",
    "go.sum",
    "go.work.sum",
    "packages.lock.json",
    "Package.resolved",
    "gradle.lockfile",
    ".terraform.lock.hcl",
    "flake.lock",
    "Podfile.lock",
    "pubspec.lock",
    "composer.lock",
}
NOT_AUTHORED = (
    "*.lock",
    "*.lockfile",
    "*.min.js",
    "*.min.mjs",
    "*.min.css",
    "*.map",
    "*.snap",
)
# Data no agent writes by hand. Not *.json, *.txt or *.html: those are often authored, so a
# data one gets a linguist-generated line in .gitattributes instead.
DATA = (
    "*.csv",
    "*.tsv",
    "*.geojson",
    "*.topojson",
    "*.jsonl",
    "*.ndjson",
    "*.gpx",
    "*.kml",
)
VENDOR_DIRS = {
    "vendor",
    "third_party",
    "third-party",
    "node_modules",
    "bower_components",
}
SNIFF = 8000
# A codegen header, not prose that mentions generated code: "@generated" anywhere, or a
# comment line that says "DO NOT EDIT" (in capitals, as generators write it) or opens with
# "auto-generated", "generated by" or "code generated" ("This file is ..." allowed first).
# In Markdown "#" is a heading, so only an HTML comment counts.
GENERATED_PHRASE = (
    rb"(?:(?i:\s*(?:this (?:file|code) (?:is|was|has been) )?"
    rb"(?:auto-?generated|generated by|code generated))|.*DO NOT EDIT)"
)
GENERATED_MARKER = re.compile(
    rb"(?i:@generated)|^\s*(?:#|//|/\*|\*|<!--|--|;)" + GENERATED_PHRASE, re.MULTILINE
)
GENERATED_MARKER_MD = re.compile(
    rb"(?i:@generated)|^\s*<!--" + GENERATED_PHRASE, re.MULTILINE
)
MARKDOWN = (".md", ".markdown", ".mdx")
HEADER_LINES = 5


def git(*args, stdin=None):
    return subprocess.run(["git", *args], input=stdin, capture_output=True, check=False)


def staged_blob(path):
    """The staged content of `path`, or None when the index has no file there.

    Read through git only, never open(): git refuses a path outside the repo, so an
    argument like ../../.ssh/id_rsa can't make the script read anything but the index.
    """
    result = git("cat-file", "blob", f":{path}")
    return (
        result.stdout if result.returncode == 0 else None
    )  # unstaged, deleted, a submodule, outside the repo


def marked_by_attributes(paths):
    """Paths .gitattributes (as staged) marks linguist-generated or linguist-vendored."""
    if not paths:
        return set()
    result = git(
        "check-attr",
        "--cached",
        "-z",
        "--stdin",
        "linguist-generated",
        "linguist-vendored",
        stdin=b"\0".join(os.fsencode(p) for p in paths) + b"\0",
    )
    fields = result.stdout.split(b"\0")
    marked = set()
    for i in range(0, len(fields) - 2, 3):
        path, _, value = fields[i : i + 3]
        if value in (b"set", b"true"):
            marked.add(os.fsdecode(path))
    return marked


def is_binary(blob):
    head = blob[:SNIFF]
    if b"\0" in head:
        return True
    try:
        head.decode("utf-8")
    except UnicodeDecodeError as e:
        return e.start < len(head) - 3  # not a character the cut at SNIFF split in two
    return False


def skip_reason(path, blob):
    name = os.path.basename(path)
    if name in LOCKFILES or any(
        fnmatch.fnmatch(name, pattern) for pattern in NOT_AUTHORED
    ):
        return "lockfile or build output"
    if any(fnmatch.fnmatch(name.lower(), pattern) for pattern in DATA):
        return "data"
    if VENDOR_DIRS.intersection(path.split("/")[:-1]):
        return "vendored"
    if is_binary(blob):
        return "binary"
    marker = (
        GENERATED_MARKER_MD if name.lower().endswith(MARKDOWN) else GENERATED_MARKER
    )
    if marker.search(b"\n".join(blob.split(b"\n", HEADER_LINES)[:HEADER_LINES])):
        return "generated-file header"
    return None


def advice(over, limit):
    target = int(limit * TARGET)
    width = max(len(path) for path, _ in over)
    rows = "\n".join(
        f"  {path:<{width}}  {tokens:>7,} tokens  ({tokens - limit:,} over; split into {math.ceil(tokens / target)}+ files)"
        for path, tokens in over
    )
    return f"""\
File token limit: {len(over)} staged file{"s are" if len(over) > 1 else " is"} over {limit:,} tokens (bytes / {CHARS_PER_TOKEN}).

{rows}

An agent has to read a file whole to change it safely; past {limit:,} tokens it reads
parts, misses the rest, and every edit rewrites more than it touches. Split each file
along its seams, aiming for under {target:,} tokens per new file:

1. Find the seams. List the file's top-level units (classes, functions, components,
   route handlers, ## sections) and group the ones that call each other or change
   together. Each group becomes one file. Don't cut by line count.
2. Code: move each group into a sibling module named for what it does (parser.py,
   validation.ts), never part2 / utils2 / misc. What's left in the original is the
   entry point that wires them together. Update every import of a moved name (search
   the repo for it); re-export from the old path only if it's a public API.
3. Tests: split the matching test file the same way, one test file per new module.
4. Markdown: move each large ## section into its own file in a folder named after the
   original, and leave the original as a short overview that links to each part.
5. Data, fixtures, long string tables: move them out of code into data files that are
   loaded at runtime. If a file is generated by a tool, mark it instead of splitting
   it: add "<path> linguist-generated" to .gitattributes and stage that.
6. Don't game it: no minifying, joining lines, deleting comments or docs, or shortening
   names to squeeze under the limit, and don't skip the hook with --no-verify.
7. Run the tests and type checks, `git add` the new files and the shortened original,
   and commit again.

Exempt: lockfiles, minified bundles, source maps, snapshots, CSV/GeoJSON-style data,
vendor/ and third_party/ folders, binaries, files marked linguist-generated or
linguist-vendored in .gitattributes, and files whose first lines carry "@generated",
or a comment saying "DO NOT EDIT" or opening with "auto-generated"."""


def main(argv):
    parser = argparse.ArgumentParser(
        prog=os.path.basename(sys.argv[0]),
        description="Fail when a staged, agent-authored file is over a token budget (bytes / 4).",
        epilog="Lockfiles, build output, binaries and generated files are skipped; see the script's docstring.",
    )
    parser.add_argument(
        "--max-tokens",
        type=int,
        default=5000,
        metavar="N",
        help="the budget per file (default 5000)",
    )
    parser.add_argument(
        "paths", nargs="*", help="files to check, normally lefthook's {staged_files}"
    )
    args = parser.parse_args(argv)
    if args.max_tokens < 1:
        parser.error("--max-tokens must be at least 1")

    attributed = marked_by_attributes(args.paths)
    over = []
    for path in args.paths:
        if path in attributed:
            continue
        blob = staged_blob(path)
        if blob is None or skip_reason(path, blob):
            continue
        if len(blob) / CHARS_PER_TOKEN > args.max_tokens:
            over.append((path, math.ceil(len(blob) / CHARS_PER_TOKEN)))

    if over:
        print(advice(over, args.max_tokens), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
